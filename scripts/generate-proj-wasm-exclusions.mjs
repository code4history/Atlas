#!/usr/bin/env node
/**
 * proj-wasm の実行時で「書き出すと例外になる」投影 CRS を、proj.db の全行について実測し、
 * `src/proj-wasm-exclusions.ts` に書く。
 *
 * なぜ要るか: proj-wasm 0.1.0-alpha8 では、PROJ（C++）の例外が wasm の外へ抜けるたびに
 * 実行時の状態が少しずつ壊れ、例外が重なると以後の呼び出しが `memory access out of bounds`
 * で失敗したり応答しなくなったりする。∴ 例外になる書き出しを、wasm に渡す前に避ける。
 *
 * - `wkt2Unavailable`: `projAsWkt`（WKT2:2019）が例外になる行。行は残し、`wkt2` を null にする
 * - `proj4Unavailable`: `projAsProjString`（PROJ 5）が例外になる行。PROJ 文字列が無い行は
 *   変換に使えないので、検索結果から除き、理由を呼び出し元へ知らせる
 *
 * 例外は 1 つの process の中で溜まるので、authority ごとに子 process で測る。
 * proj-wasm の版を変えたら作り直す（`tests/proj-wasm-exclusions.test.ts` が proj.db の
 * SHA-256 と版の一致を検査する）。
 *
 * Usage: node scripts/generate-proj-wasm-exclusions.mjs [--out=src/proj-wasm-exclusions.ts]
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PJ_TYPE_PROJECTED_CRS = 15;
const CALL_TIMEOUT_MS = 15_000;

const require = createRequire(import.meta.url);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function parseArgs(argv) {
  const options = { out: join(repoRoot, "src/proj-wasm-exclusions.ts") };
  for (const arg of argv) {
    const [key, value] = arg.split("=");
    if (key === "--out") options.out = resolve(value);
    else if (key === "--child") options.child = value;
    else if (key === "--result") options.result = value;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

function withTimeout(promise) {
  let timer;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(`timed out after ${CALL_TIMEOUT_MS} ms`)), CALL_TIMEOUT_MS);
    }),
  ]).finally(() => clearTimeout(timer));
}

async function loadProj() {
  const proj = await import("proj-wasm");
  await proj.init({ workers: 1 });
  return proj;
}

async function projectedRows(proj) {
  const rows = await proj.projGetCrsInfoListFromDatabase({});
  return rows.filter((row) => row.type === PJ_TYPE_PROJECTED_CRS);
}

/** 子 process: 1 つの authority の全行を逐次に書き出し、例外になったものを result に書く。 */
async function runChild(authority, resultPath) {
  const proj = await loadProj();
  const rows = authority === "*"
    ? []
    : (await projectedRows(proj)).filter((row) => row.authName === authority);
  const result = { authorities: [], wkt2Unavailable: [], proj4Unavailable: [] };

  if (authority === "*") {
    result.authorities = [...new Set((await projectedRows(proj)).map((row) => row.authName))].sort();
  }

  for (const row of rows) {
    const id = `${row.authName}:${row.code}`;
    const pj = await withTimeout(proj.projCreateFromDatabase({
      auth_name: row.authName,
      code: row.code,
      category: proj.PJ_CATEGORY_CRS,
    }));
    try {
      await withTimeout(proj.projAsWkt({ pj, type: proj.PJ_WKT2_2019, options: null }));
    } catch (error) {
      if (String(error?.message).startsWith("timed out")) throw error;
      result.wkt2Unavailable.push(id);
    }
    try {
      const text = await withTimeout(proj.projAsProjString({ pj, type: proj.PJ_PROJ_5, options: null }));
      if (typeof text !== "string" || text.length === 0) {
        result.proj4Unavailable.push({ id, reason: "PROJ string export returned no text" });
      }
    } catch (error) {
      if (String(error?.message).startsWith("timed out")) throw error;
      result.proj4Unavailable.push({ id, reason: String(error?.message ?? error) });
    }
  }

  writeFileSync(resultPath, JSON.stringify(result));
}

function runInChild(authority, workDir) {
  const resultPath = join(workDir, `${authority === "*" ? "authorities" : authority}.json`);
  const child = spawnSync(process.execPath, [
    fileURLToPath(import.meta.url),
    `--child=${authority}`,
    `--result=${resultPath}`,
  ], { cwd: repoRoot, stdio: ["ignore", "ignore", "inherit"], timeout: 600_000 });
  if (child.status !== 0) {
    throw new Error(`Measuring ${authority} failed (exit ${child.status ?? child.signal})`);
  }
  return JSON.parse(readFileSync(resultPath, "utf8"));
}

function renderModule(table) {
  return [
    "// Generated by scripts/generate-proj-wasm-exclusions.mjs. Do not edit by hand.",
    "// Projected CRS rows whose export throws inside the bundled proj-wasm runtime.",
    "// Regenerate when proj-wasm changes (tests/proj-wasm-exclusions.test.ts checks the version and proj.db).",
    "",
    "export interface ProjWasmExclusionTable {",
    "  projWasmVersion: string;",
    "  projDbSha256: string;",
    "  /** Rows whose WKT2:2019 export throws. They stay in the result with `wkt2: null`. */",
    "  wkt2Unavailable: string[];",
    "  /** Rows whose PROJ string export throws. They are left out of the result. */",
    "  proj4Unavailable: Array<{ id: string; reason: string }>;",
    "}",
    "",
    `export const projWasmExclusions: ProjWasmExclusionTable = ${JSON.stringify(table, null, 2)};`,
    "",
  ].join("\n");
}

function compareIds(left, right) {
  return left.localeCompare(right, "en", { numeric: true });
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.child) {
    await runChild(options.child, options.result);
    process.exit(0);
  }

  const projWasmDist = dirname(require.resolve("proj-wasm"));
  const projWasmVersion = JSON.parse(readFileSync(join(projWasmDist, "..", "package.json"), "utf8")).version;
  const projDbSha256 = createHash("sha256").update(readFileSync(join(projWasmDist, "proj.db"))).digest("hex");

  const workDir = mkdtempSync(join(tmpdir(), "atlas-proj-wasm-exclusions-"));
  try {
    const { authorities } = runInChild("*", workDir);
    const wkt2Unavailable = [];
    const proj4Unavailable = [];
    for (const authority of authorities) {
      const result = runInChild(authority, workDir);
      wkt2Unavailable.push(...result.wkt2Unavailable);
      proj4Unavailable.push(...result.proj4Unavailable);
      console.log(`${authority}: wkt2 ${result.wkt2Unavailable.length}, proj4 ${result.proj4Unavailable.length}`);
    }

    wkt2Unavailable.sort(compareIds);
    proj4Unavailable.sort((left, right) => compareIds(left.id, right.id));
    const table = { projWasmVersion, projDbSha256, wkt2Unavailable, proj4Unavailable };
    writeFileSync(options.out, renderModule(table));
    console.log(`Wrote ${options.out}: wkt2 ${wkt2Unavailable.length}, proj4 ${proj4Unavailable.length}`);
  } finally {
    rmSync(workDir, { recursive: true, force: true });
  }
  process.exit(0);
}

await main();
